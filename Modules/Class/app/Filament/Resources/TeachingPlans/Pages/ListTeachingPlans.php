<?php

namespace Modules\Class\Filament\Resources\TeachingPlans\Pages;

use App\Filament\Concerns\HasPageHelp;
use Filament\Actions\CreateAction;
use Filament\Resources\Pages\ListRecords;
use Modules\Class\Filament\Resources\TeachingPlans\TeachingPlanResource;

class ListTeachingPlans extends ListRecords
{
    use HasPageHelp;

    protected static string $resource = TeachingPlanResource::class;

    protected function getHeaderActions(): array
    {
        return [
            CreateAction::make()
                ->modalWidth('4xl'),
        ];
    }

    protected function pageHelpKey(): string
    {
        return 'class.teaching-plans';
    }

    protected function defaultPageHelp(): string
    {
        $tenant = config('sarasystem.tenant_label');

        return <<<TEXT
        طرح درس چیست؟
        طرح درس فهرست مرتب سرفصل‌های یک دوره یا درس است و برای هر سرفصل مشخص می‌کند چند جلسه وقت می‌گیرد؛ مثلاً «فصل ۱: اعداد صحیح، ۲ جلسه» و پس از آن «فصل ۲: کسرها، ۳ جلسه». طرح درس یک بار برای همه‌ی سازمان تعریف می‌شود و هر تعداد کلاس در هر {$tenant} می‌تواند از آن پیروی کند.

        کاربرد طرح درس در این سامانه
        • در «برنامه»ی هر کلاس، در فیلد «طرح درس» انتخاب می‌شود که جلسه‌های آن برنامه از کدام طرح پیروی کنند.
        • سامانه سرفصل‌های تمام‌نشده را به ترتیب روی جلسه‌های آینده‌ی همان برنامه پیش‌بینی می‌کند و در فهرست جلسه‌ها با «برنامه: …» نشان می‌دهد.
        • مدرس هنگام ثبت «مطالب جلسه» سرفصل‌هایی را که تمام شد علامت می‌زند. سرفصلی که تمام نشده باشد خودبه‌خود به جلسه‌ی بعد می‌رود؛ اگر جلسه‌ای لغو شود هم پیش‌بینی جابه‌جا می‌شود.
        • در «برنامه»ی کلاس پیشرفت هر برنامه دیده می‌شود، مثلاً «پیشرفت: ۳ از ۸ سرفصل».

        هدف از ساختن طرح درس
        • همه‌ی کلاس‌های یک درس از یک نقشه پیروی کنند.
        • مدرس پیش از هر جلسه بداند باید چه چیزی درس بدهد.
        • مدیر آموزش ببیند هر کلاس از برنامه جلوتر است یا عقب‌تر.

        این صفحه چه کاری می‌کند؟
        با «ایجاد» طرح تازه بسازید: عنوان، درس (اختیاری؛ برنامه‌ای که درسش انتخاب شده فقط طرح‌های همان درس و طرح‌های بدون درس را پیشنهاد می‌کند)، توضیحات، و سرفصل‌ها به ترتیب، هر کدام با تعداد جلسه. ترتیب سرفصل‌ها را با کشیدن عوض کنید. ستون «جلسه‌ها» جمع جلسه‌های سرفصل‌هاست و «برنامه‌ها» تعداد برنامه‌هایی است که از این طرح پیروی می‌کنند. طرحی که دیگر به کار نمی‌آید را غیرفعال کنید تا در برنامه‌های تازه پیشنهاد نشود.

        تغییر سرفصل‌ها پیش‌بینی همه‌ی کلاس‌هایی را که از این طرح پیروی می‌کنند فوراً عوض می‌کند، ولی آنچه در جلسه‌های گذشته ثبت شده سر جایش می‌ماند.
        TEXT;
    }
}
